"""Write backend/requirements.lock: exact versions of the backend's dependency
closure (runtime + dev), as installed in the current venv.

    .venv/Scripts/python scripts/lock_requirements.py

Environment markers are evaluated for the Docker image (Linux, CPython 3.11),
so Windows-only packages (e.g. colorama) are left out. A Linux-only package
that is not installed here cannot be pinned; it is reported and the script
fails. The file is used as a pip constraints file (``-c``), so the Docker
image installs only the runtime part.
"""
from __future__ import annotations

import sys
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
LOCK_PATH = ROOT / "backend" / "requirements.lock"
PROJECT = "commitments-extractor-backend"
PROJECT_EXTRAS = frozenset({"dev"})
TARGET_ENVIRONMENT = {
    "sys_platform": "linux",
    "platform_system": "Linux",
    "os_name": "posix",
    "platform_machine": "x86_64",
    "python_version": "3.11",
    "python_full_version": "3.11.0",
    "implementation_name": "cpython",
    "platform_python_implementation": "CPython",
}
HEADER = (
    "# Exact versions of the backend's dependencies (runtime + dev), generated by\n"
    "# scripts/lock_requirements.py from the tested venv. Use as constraints:\n"
    "#   pip install -c requirements.lock .            (Docker, runtime only)\n"
    "#   pip install -c backend/requirements.lock -e \"backend[dev]\"\n"
)


def _applies(requirement: Requirement, extras: frozenset[str]) -> bool:
    if requirement.marker is None:
        return True
    return any(requirement.marker.evaluate({**TARGET_ENVIRONMENT, "extra": extra}) for extra in extras | {""})


def closure() -> tuple[dict[str, str], list[str]]:
    """Pinned versions by package name, and requirements that are not installed."""
    pinned: dict[str, str] = {}
    missing: list[str] = []
    pending = [(PROJECT, PROJECT_EXTRAS)]
    while pending:
        name, extras = pending.pop()
        for raw in distribution(name).requires or []:
            requirement = Requirement(raw)
            key = canonicalize_name(requirement.name)
            if not _applies(requirement, extras) or key in pinned:
                continue
            try:
                pinned[key] = distribution(requirement.name).version
            except PackageNotFoundError:
                missing.append(raw)
                continue
            pending.append((requirement.name, frozenset(requirement.extras)))
    return pinned, missing


def main() -> int:
    pinned, missing = closure()
    if missing:
        print("not installed, cannot pin:", ", ".join(missing), file=sys.stderr)
        return 1
    lines = [f"{name}=={version}" for name, version in sorted(pinned.items())]
    LOCK_PATH.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines)} packages -> {LOCK_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
